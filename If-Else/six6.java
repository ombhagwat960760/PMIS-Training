package ifelse;

public class six6 {

	public static void main(String[] args) {
		int m=33;
		
		if(m>89&&m<=100) {
			System.out.println("Grade A");
		}
		else if(m>=75 && m<=89) {
			System.out.println("Grade B");
		}
		else if(m>=60 && m<=74) {
			System.out.println("Grade C");
		}
		else if(m>=35 && m<=59) {
			System.out.println("Grade D");
		}
		else {
			System.out.println("Grade Fail");
		}

	}

}
